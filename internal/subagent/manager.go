// defaultMaxConcurrent caps the number of active subagents the LLM
// can have running at once. Set deliberately low — the LLM can
// re-spawn after one completes (via the failed reason=too_many_subagents
// path), and the cap exists to prevent runaway parallelism that
// would N× the API rate limit hit.
//
// See docs/prd/feature-subagent.md §8 risk "并发 spawn N 个子" for
// the design rationale.
const defaultMaxConcurrent = 3

// Runner is the LLM-execution side of subagent spawning. In
// production cmd/seek wires it to a function that builds a fresh
// pkg/agent.Agent + calls Prompt with the supplied prompt; in unit
// tests it's a stub that simulates summary / error / cancellation
// paths.
//
// Contract — Runner MUST:
//
//   - Respect ctx cancellation (return ctx.Err() promptly when ctx
//     is Done) so Manager.Kill / parent turn cancellation work.
//   - Record every turn's Usage on the supplied Tracker so the
//     parent's transitive Cumulative() captures the child cost.
//   - Return a non-empty Summary on success, OR return an error.
//     Empty summary + nil error is a contract violation.
//
// Runner MUST NOT:
//
//   - Mutate the supplied Policy (use it only for Check calls).
//   - Hold references to RunnerJob fields after returning.
//   - Panic — panics in Runner crash the seek process. Defensive
//     recover() lives in the production wrapper, not here.
type Runner func(ctx context.Context, job RunnerJob) (RunnerResult, error)

// RunnerJob is the immutable bundle Manager hands to Runner. All
// fields are set up by Manager before Spawn calls the Runner: child
// Policy is already restricted via Policy.Spawn, child Tracker is
// already AdoptChild'd by the parent, the system prompt is already
// composed via sysprompt.ComposeSubagent, the session dir is
// already mkdir'd.
type RunnerJob struct {
	SubSid       string
	SystemPrompt string
	UserPrompt   string
	// SessionDir is the per-subagent directory where Runner writes
	// its transcript.jsonl (and any plan / checkpoint artefacts
	// generated by tools the subagent calls). See PRD §3.3.
	SessionDir string
	Tracker    *cache.Tracker
	Policy     *permission.Policy
	// ToolNames is the filtered tool allow-list per the template.
	// Runner uses this to construct the child tools.Registry
	// (typically by re-registering the parent's tool instances
	// keyed by name).
	ToolNames []string
	// Provider is the resolved routing lane ("" = inherit the
	// parent session's provider). Set from SpawnArgs via
	// ResolveRoute — never the raw tool-call value, which
	// validation has already rejected when unknown.
	Provider string
	// Model is the resolved model id. Empty exactly when Provider
	// is empty (inherit the parent's live session model).
	Model string
}

// RunnerResult is what Runner returns on success. Summary is the
// subagent's final assistant message body (NOT yet wrapped in the
// [agent: completed] wire format — that's Manager's job). Turns is
// the count of LLM turns the subagent took; goes into the wire-
// format footer.
type RunnerResult struct {
	Summary string
	Tokens  Tokens
	Turns   int
}

// ManagerOpts configures a new Manager.
//
// ProjectAbsPath / ParentTracker / ParentPolicy are bound at
// construction — the path is immutable, and the pointers themselves
// don't change (Tracker / Policy own their own state mutation under
// their own locks).
//
// ParentSid / ProjectSection / SkillManifest / ParentToolNames are
// supplied as func() closures, not values, because:
//
//   - ParentSid: /compact forks a new session with a new ID; the
//     closure pattern (typed by main.go's planBridge.sessionID) ensures
//     subagents spawned after /compact use the live ID.
//   - ProjectSection: stable today, but the closure form keeps the
//     contract uniform with the rest.
//   - SkillManifest: skill_commit + /new hot-reloads the manifest;
//     subagents spawned after the reload must see the new manifest.
//   - ParentToolNames: the parent's Registry is built in stages
//     (initial set → agent.New → plan/propose added) so capturing a
//     snapshot at Manager construction would miss tools added later.
//     reg.Names() is also where the agent tool itself appears — the
//     template Filter strips it universally so the recursion guard
//     stays intact.
//
// SessionCtx is the process/session-level context that background
// spawns (SpawnBackground) derive from — NEVER the calling turn's
// ctx, otherwise the parent turn returning would cancel the child
// and "background" would be a lie (feature-orchestration PRD §4.1
// D1, the 柱 K bgjob D5 lesson lifted to agent level). Optional at
// construction: sync-only Managers leave it nil, and SpawnBackground
// refuses with a wire-format failure when it's missing.
//
// MaxConcurrent defaults to 3 when zero. Runner is required.
type ManagerOpts struct {
	ProjectAbsPath string
	ParentTracker  *cache.Tracker
	ParentPolicy   *permission.Policy
	MaxConcurrent  int
	Runner         Runner
	// SessionCtx anchors background spawns to the seek process
	// lifetime (session dies → jobs die; zero-daemon discipline).
	// cmd/seek passes the signal.NotifyContext ctx here.
	SessionCtx context.Context

	// Now is the time source used for sub_sid generation and event
	// timestamps. Optional — falls back to time.Now if nil.
	// Tests inject a stub so sub-sids are reproducible.
	Now func() time.Time

	// SessionDate is the parent's fixed session date string (e.g.
	// "Wednesday, 2026-06-03"), captured once at session start and
	// passed verbatim into every subagent's system prompt. It is a
	// static value, NOT derived from Now(): it must stay byte-identical
	// to the parent's prompt (the §3.6.1 header-inheritance invariant),
	// and recomputing it from Now() at Spawn time would drift if the
	// session spans midnight. Empty in tests that don't exercise the
	// prompt body.
	SessionDate string

	// Dynamic accessors — called at each Spawn so RebuildAgent,
	// skill hot-reload, and session compaction (fork-new-SID) pick
	// up fresh values. See struct doc above for the rationale per
	// field. All are required.
	ParentSidFn       func() string
	ProjectSectionFn  func() string
	SkillManifestFn   func() string
	ParentToolNamesFn func() []string

	// AgentTypes is the typed-agent registry from the P2-a loader
	// (agenttypes.Load, frozen at session start). Since P2-c EVERY
	// entry routes through the same typed path in Manager.resolveType
	// — file-scope customs via the D13 gate (custom.go), built-ins
	// byte-identically to the retired compile-time table, config
	// clones (OriginConfig) carrying their routing knobs. nil =
	// built-ins only via the compile-time fallback (the pre-P2-b
	// behaviour of callers that don't set it).
	AgentTypes *agenttypes.Set
}

// Manager owns the subagents.jsonl index + the in-flight map for
// one (project, parent-session) pair. Methods are concurrent-safe;
// the LLM can issue parallel `agent` tool calls in one turn and
// each Spawn runs in its own goroutine.
//
// Background spawns (SpawnBackground, feature-orchestration PRD
// §4.1) add three pieces on top: a bgWg tracking the detached
// goroutines (so Shutdown can wait for their terminal events to
// land), and a notice inbox (FIFO queue + cap-1 wake channel) that
// carries terminal results to the parent session's next Prompt via
// the Notifier PrePrompt hook and wakes the TUI loop.
type Manager struct {
	opts ManagerOpts

	mu     sync.Mutex
	active map[string]*inFlight

	// bgWg tracks SpawnBackground goroutines. Shutdown cancels all
	// active inFlights then waits here so every background child
	// writes its `failed reason=canceled` terminal event before the
	// process exits (clean-exit contract, PRD §4.1 D3).
	bgWg sync.WaitGroup

	noticeMu sync.Mutex
	pending  []BackgroundNotice
	wakeCh   chan struct{}
}

// inFlight is the per-spawn mutable state that lives only between
// the `started` event and the terminal event. cancel terminates
// the Runner; killedByUser distinguishes Manager.Kill (explicit
// user action → `killed` event) from generic ctx.Canceled (parent
// turn cancelled → `failed reason=canceled` event).
type inFlight struct {
	cancel       context.CancelFunc
	killedByUser bool
}

// NewManager constructs a Manager. Returns an error only for
// programmer errors (nil dependencies, missing parent sid) — the
// goal is fail-loud on misuse, not gracefully degrade.
func NewManager(opts ManagerOpts) (*Manager, error) {
	if opts.ProjectAbsPath == "" {
		return nil, errors.New("subagent: NewManager: ProjectAbsPath required")
	}
	if opts.ParentTracker == nil {
		return nil, errors.New("subagent: NewManager: ParentTracker required")
	}
	if opts.ParentPolicy == nil {
		return nil, errors.New("subagent: NewManager: ParentPolicy required")
	}
	if opts.Runner == nil {
		return nil, errors.New("subagent: NewManager: Runner required")
	}
	if opts.ParentSidFn == nil {
		return nil, errors.New("subagent: NewManager: ParentSidFn required")
	}
	if opts.ProjectSectionFn == nil {
		return nil, errors.New("subagent: NewManager: ProjectSectionFn required")
	}
	if opts.SkillManifestFn == nil {
		return nil, errors.New("subagent: NewManager: SkillManifestFn required")
	}
	if opts.ParentToolNamesFn == nil {
		return nil, errors.New("subagent: NewManager: ParentToolNamesFn required")
	}
	if opts.MaxConcurrent == 0 {
		opts.MaxConcurrent = defaultMaxConcurrent
	}
	if opts.Now == nil {
		opts.Now = func() time.Time { return time.Now().UTC() }
	}
	return &Manager{
		opts:   opts,
		active: make(map[string]*inFlight),
		wakeCh: make(chan struct{}, 1),
	}, nil
}

// SpawnArgs is the per-call input shape. ParentTurn carries the
// current turn index from the caller's perspective (typically the
// parent agent loop's turn counter) so the index event can be
// cross-referenced with the parent transcript.
type SpawnArgs struct {
	Description string
	Prompt      string
	Type        Type
	ParentTurn  int
	// WorktreePath is set when isolation:"worktree" is in effect
	// (the agent tool handles the worktree create call BEFORE
	// invoking Spawn). Empty for isolation:"none". Goes into the
	// started event for the /worktrees panel's cross-reference.
	WorktreePath string
	// Provider / Model are the optional per-call routing params
	// (feature-orchestration.md §4.2). Both empty = inherit the
	// parent session's lane unchanged. Validated via ResolveRoute
	// in Spawn step 1 — raw tool-call values arrive here verbatim
	// so Manager stays the single validation point.
	Provider string
	Model    string
}

// Spawn launches one subagent and blocks until it terminates.
// Returns a Result whose Summary field is ALWAYS a well-formed
// wire-format string (success path = "[agent: completed] ...",
// any failure path = "[agent: failed reason=...] ...") — the
// caller can return it verbatim as a tool result.
//
// Concurrency model:
//
//   - Validation and the budget gate run under m.mu briefly.
//   - The Runner runs with m.mu released; it can take seconds to
//     minutes (LLM generation time).
//   - Terminal-event emission re-acquires m.mu only to mutate
//     m.active; the appendEvent call to the index is serialised
//     globally via indexLock.
//
// Spawn is sync, but the LLM can call the `agent` tool multiple
// times in one turn → multiple Spawns running in parallel
// goroutines. The MaxConcurrent gate caps simultaneous in-flights.
//
// Spawn and SpawnBackground share steps 1–8 via begin and steps
// 9–11 via runAndFinish; the ONLY divergence is which ctx the
// child runs under (caller turn ctx vs ManagerOpts.SessionCtx)
// and where the Result goes (return value vs notice inbox).
func (m *Manager) Spawn(ctx context.Context, args SpawnArgs) Result {
	sp, fail := m.begin(ctx, args, false)
	if fail != nil {
		return *fail
	}
	return m.runAndFinish(sp, false)
}

// SpawnBackground launches one subagent detached and returns
// IMMEDIATELY with a "[agent: background started sub-sid=...]"
// wire-format Result — the parent turn keeps going while the child
// runs (feature-orchestration PRD §4.1 D1).
//
// The child goroutine is bound to ManagerOpts.SessionCtx, NOT the
// caller's ctx: cancelling the parent turn (Esc) must never kill a
// background child. Kill / the capacity gate / ActiveCount treat
// sync and background spawns identically (same m.active map +
// MaxConcurrent door).
//
// On terminal state the goroutine writes the same subagents.jsonl
// event kinds as the sync path (no new event types) and enqueues a
// BackgroundNotice. Delivery into the parent session is the
// Notifier PrePrompt hook's job (next Prompt prepends the notice
// as a <context> message); the TUI gets a WakeCh signal for
// immediate UI feedback. See D2 for the notification protocol.
func (m *Manager) SpawnBackground(args SpawnArgs) Result {
	if m.opts.SessionCtx == nil {
		return failResult("", "spawn_error",
			"background spawn unavailable: ManagerOpts.SessionCtx not wired by host")
	}
	sp, fail := m.begin(m.opts.SessionCtx, args, true)
	if fail != nil {
		return *fail
	}
	m.bgWg.Add(1)
	go func() {
		defer m.bgWg.Done()
		res := m.runAndFinish(sp, true)
		m.enqueueNotice(BackgroundNotice{
			SubSid:      res.SubSid,
			Description: args.Description,
			Status:      res.Status,
			Summary:     res.Summary,
		})
	}()
	return Result{
		SubSid:  sp.subSid,
		Summary: FormatBackgroundStarted(sp.subSid, args.Description),
		Status:  StatusActive,
	}
}

// spawnSetup is the per-spawn state produced by begin — everything
// steps 1–8 allocated, with the child registered in m.active. The
// name mirrors the step numbering of the original Spawn body so the
// split stays auditable against feature-subagent.md §3.
type spawnSetup struct {
	args         SpawnArgs
	subSid       string
	sessionDir   string
	indexPath    string
	childPolicy  *permission.Policy
	childTracker *cache.Tracker
	systemPrompt string
	toolNames    []string
	// Provider / Model carry the RESOLVED route from ResolveRoute
	// (begin step 1) through to the RunnerJob — never the raw
	// tool-call values, which validation has already rejected.
	// Both empty = inherit the parent session's lane.
	Provider string
	Model    string
	runCtx   context.Context
	cancel   context.CancelFunc
	inf      *inFlight
}

// begin runs the shared steps 1–8: validate, capacity-gate, child
// Policy/Tracker, sub_sid + session dir, system prompt, `started`
// index event, active registration under a child ctx derived from
// parentCtx (the CALLER's ctx for sync Spawn, SessionCtx for
// SpawnBackground — the one line that makes background real).
// background records the spawn mode on the `started` event so the
// fold (and /agents) can present background rows with their terminal
// states; terminal events stay identical for both modes.
// A non-nil *Result return means the spawn was refused before the
// runner started (wire-format failure, no active entry); on success
// the caller owns the child lifecycle from step 9.
func (m *Manager) begin(parentCtx context.Context, args SpawnArgs, background bool) (*spawnSetup, *Result) {
	// Step 1: validate args. Failures here produce a wire-format
	// result with no index event — the spawn never happened.
	//
	// Type resolution goes through resolveType (P2-b): a custom
	// file-defined type (or a file shadowing a built-in name) is
	// adapted through the D13 gate; built-ins keep the compile-time
	// template path byte-identical. Gate failures (loosening
	// workflow, forbidden tools, unknown provider) fail the spawn
	// with the gate's message — same wire-format class as an unknown
	// type.
	tmpl, def, terr := m.resolveType(args.Type)
	if terr != nil {
		r := failResult("", "spawn_error", terr.Error())
		return nil, &r
	}
	if args.Description == "" {
		r := failResult("", "spawn_error", "description required")
		return nil, &r
	}
	if args.Prompt == "" {
		r := failResult("", "spawn_error", "prompt required")
		return nil, &r
	}
	// Routing params: unknown provider / model is a validation
	// failure, same class as unknown subagent_type (feature-
	// orchestration.md §4.2). Route keeps "" provider for the
	// inherit path so the Runner's default lane is byte-identical
	// to the pre-routing behaviour.
	//
	// A custom Definition's provider/model (D11) fill the gaps the
	// per-call params leave; explicit call params win — the caller's
	// more specific request at call time (routing is not a
	// permission axis, so override is not a D13 concern). The MERGED
	// pair is re-validated by ResolveRoute: def provider + call model
	// from different lanes is a clear error, not a mispriced spawn.
	provider, model := args.Provider, args.Model
	if def != nil {
		if provider == "" {
			provider = def.Provider
		}
		if model == "" {
			model = def.Model
		}
	}
	route, err := ResolveRoute(provider, model)
	if err != nil {
		r := failResult("", "spawn_error", err.Error())
		return nil, &r
	}

	// Step 2: capacity gate. Held BRIEFLY under m.mu — the Runner
	// path runs lock-free, so a slow subagent doesn't block other
	// Spawn calls from running their own capacity check.
	m.mu.Lock()
	if len(m.active) >= m.opts.MaxConcurrent {
		n := len(m.active)
		m.mu.Unlock()
		r := failResult("", "too_many_subagents",
			fmt.Sprintf("%d active, retry after one completes", n))
		return nil, &r
	}
	m.mu.Unlock()

	// Step 3: build child Policy via monotonic-only Spawn. The
	// subagent's cwd defaults to the parent's; isolation:"worktree"
	// (when wired in M11.1) will override this to the worktree
	// path BEFORE Spawn is called — Manager doesn't know about
	// worktree paths directly. tmpl comes from step 1's resolveType.
	cwd := m.opts.ParentPolicy.Cwd()
	if args.WorktreePath != "" {
		cwd = args.WorktreePath
	}
	childPolicy, err := m.opts.ParentPolicy.Spawn(cwd, tmpl.Restriction)
	if err != nil {
		r := failResult("", "spawn_error", err.Error())
		return nil, &r
	}

	// Step 4: create + adopt child Tracker. The parent's
	// CumulativeCost from this point on transitively includes the
	// child's Record calls; AdoptChild is safe to call on a fresh
	// Tracker per the contract in cache.AdoptChild's doc.
	childTracker := cache.New()
	m.opts.ParentTracker.AdoptChild(childTracker)

	// Step 5: allocate sub_sid + session directory. Resolve the
	// parent sid via the supplied closure so /compact-forked sessions
	// pick up the new ID. Empty result is a programmer error (the
	// host program should not allow Spawn with no active session).
	parentSid := m.opts.ParentSidFn()
	if parentSid == "" {
		r := failResult("", "spawn_error", "no active parent session (host did not seed ParentSidFn)")
		return nil, &r
	}
	now := m.opts.Now()
	subSid := newSubSid(now)
	sessionDir, err := paths.SubagentSessionDir(m.opts.ProjectAbsPath, parentSid, subSid)
	if err != nil {
		r := failResult(subSid, "spawn_error", err.Error())
		return nil, &r
	}
	if err := os.MkdirAll(sessionDir, 0o755); err != nil {
		r := failResult(subSid, "spawn_error", "mkdir session dir: "+err.Error())
		return nil, &r
	}

	// Step 6: compose system prompt. Header is byte-identical to
	// the parent's segments 1-3 (sysprompt.Compose guarantees
	// determinism for the same inputs); the trailing role + summary
	// hint differs per template. Project section + skill manifest
	// are resolved fresh each spawn so skill_commit + /new is
	// reflected in the next subagent's prompt.
	systemPrompt := sysprompt.ComposeSubagent(sysprompt.Header{
		Cwd:            cwd,
		ProjectSection: m.opts.ProjectSectionFn(),
		SkillManifest:  m.opts.SkillManifestFn(),
		Date:           m.opts.SessionDate,
	}, tmpl.Role(args.Description))

	// Step 7: emit `started` event BEFORE registering in active.
	// If the append fails we abort without leaving an orphan in
	// the map.
	indexPath, err := paths.SubagentsIndex(m.opts.ProjectAbsPath)
	if err != nil {
		r := failResult(subSid, "spawn_error", err.Error())
		return nil, &r
	}
	if err := appendEvent(indexPath, event{
		Kind:         "started",
		SubSid:       subSid,
		ParentSid:    parentSid,
		ParentTurn:   args.ParentTurn,
		TS:           now,
		Type:         args.Type,
		Description:  args.Description,
		WorktreePath: args.WorktreePath,
		Background:   background,
	}); err != nil {
		r := failResult(subSid, "spawn_error", "write index: "+err.Error())
		return nil, &r
	}

	// Step 8: register in m.active under a child ctx we own.
	runCtx, cancel := context.WithCancel(parentCtx)
	inf := &inFlight{cancel: cancel}
	m.mu.Lock()
	m.active[subSid] = inf
	m.mu.Unlock()

	return &spawnSetup{
		args:         args,
		subSid:       subSid,
		sessionDir:   sessionDir,
		indexPath:    indexPath,
		childPolicy:  childPolicy,
		childTracker: childTracker,
		systemPrompt: systemPrompt,
		toolNames:    tmpl.Filter(m.opts.ParentToolNamesFn()),
		Provider:     route.Provider,
		Model:        route.Model,
		runCtx:       runCtx,
		cancel:       cancel,
		inf:          inf,
	}, nil
}

// resolveType looks up the spawn-time Template for a subagent_type
// (P2-c, feature-orchestration.md §5): every definition in
// ManagerOpts.AgentTypes — built-in, config-override clone, or file
// scope — routes through the SAME typed path (resolveTypedDef). The
// built-ins' entries in a Load()ed Set are the compile-time
// Definitions themselves, so this path is byte-identical to the old
// compile-time-template special case (locked by
// TestSpawn_BuiltinBytePathWithSetWired); the special case itself
// retired in P2-c ("内置三模板进默认路由").
//
// The compile-time table remains only as the fallback for Managers
// with no AgentTypes wired (nil = pre-P2-b callers, tests) and as the
// byte-identity oracle for the tests.
//
// The returned *agenttypes.Definition is non-nil whenever the Set
// resolved the name; begin merges its provider/model routing knobs
// into the per-call params (empty knobs on plain built-ins — a
// no-op). A non-nil error fails the spawn before any state is
// allocated (unknown type name, or a gate rejection — the message is
// the gate's own).
func (m *Manager) resolveType(t Type) (Template, *agenttypes.Definition, error) {
	if m.opts.AgentTypes != nil {
		if def := m.opts.AgentTypes.Get(string(t)); def != nil {
			tmpl, err := m.resolveTypedDef(def)
			if err != nil {
				return Template{}, def, err
			}
			return tmpl, def, nil
		}
	}
	tmpl, ok := TemplateFor(t)
	if !ok {
		return Template{}, nil, fmt.Errorf("unknown subagent_type %q", t)
	}
	return tmpl, nil, nil
}

// resolveTypedDef is the one gate every Set-loaded definition passes
// through, whatever its origin (P2-c):
//
//   - shape (name, tighten-only workflow, forbidden tools) and
//     provider/model lane validity are checked for ALL origins — the
//     gate must not trust its feeders (a hand-built Set can carry
//     anything);
//   - the unknown-tools DEGRADE (drop the whitelist, fall back to the
//     general-purpose toolset) applies ONLY to file scopes (project /
//     user). Built-ins and their config clones keep the historical
//     intersect-with-parent semantics inside Template.Filter: a parent
//     registry without webfetch gets explore-minus-webfetch, NOT a
//     silently widened general-purpose set — the acceptance-#5
//     byte-path guarantee for "no agents files + empty config".
func (m *Manager) resolveTypedDef(def *agenttypes.Definition) (Template, error) {
	if err := customTypeShapeErr(def); err != nil {
		return Template{}, err
	}
	if def.Provider != "" || def.Model != "" {
		if _, err := ResolveRoute(def.Provider, def.Model); err != nil {
			return Template{}, err
		}
	}
	switch def.Origin {
	case agenttypes.OriginProject, agenttypes.OriginUser:
		return ResolveCustomType(def, m.opts.ParentToolNamesFn())
	}
	return defToTemplate(def), nil
}

// runAndFinish runs the shared steps 9–11: invoke the Runner,
// release the active slot, classify the outcome, write the terminal
// index event, and format the Result. background selects the
// wire-format family: the sync path returns
// "[agent: completed/failed ...]" to the calling turn as its tool
// result; the background path's Result flows into the notice inbox
// as "[agent: background done/failed ...]" for the Notifier.
// Terminal index events are IDENTICAL for both paths.
func (m *Manager) runAndFinish(sp *spawnSetup, background bool) Result {
	// Step 9: run. This blocks. Recover from panics so a buggy
	// Runner can't take down the seek process — convert panic to
	// a failed event with reason=spawn_error.
	var (
		runResult RunnerResult
		runErr    error
	)
	func() {
		defer func() {
			if r := recover(); r != nil {
				runErr = fmt.Errorf("runner panic: %v", r)
			}
		}()
		runResult, runErr = m.opts.Runner(sp.runCtx, RunnerJob{
			SubSid:       sp.subSid,
			SystemPrompt: sp.systemPrompt,
			UserPrompt:   sp.args.Prompt,
			SessionDir:   sp.sessionDir,
			Tracker:      sp.childTracker,
			Policy:       sp.childPolicy,
			ToolNames:    sp.toolNames,
			Provider:     sp.Provider,
			Model:        sp.Model,
		})
	}()
	sp.cancel() // release any goroutines depending on runCtx

	// Step 10: pop from active under mu, capturing the killed
	// flag if set.
	m.mu.Lock()
	killed := sp.inf.killedByUser
	delete(m.active, sp.subSid)
	m.mu.Unlock()

	// Step 11: classify outcome → terminal event + wire-format
	// result. Order matters: explicit kill takes precedence over
	// ctx.Canceled detection because Kill sets the flag THEN
	// cancels, so a Kill is observable both ways.
	endTS := m.opts.Now()

	switch {
	case runErr == nil && runResult.Summary != "":
		// Happy path.
		tokens := runResult.Tokens
		_ = appendEvent(sp.indexPath, event{
			Kind: "completed", SubSid: sp.subSid, TS: endTS, Tokens: &tokens,
		})
		if background {
			return Result{
				SubSid:  sp.subSid,
				Summary: FormatBackgroundDone(sp.subSid, runResult.Summary, runResult.Turns, tokens),
				Status:  StatusCompleted,
				Tokens:  tokens,
			}
		}
		return Result{
			SubSid:  sp.subSid,
			Summary: FormatCompleted(sp.subSid, runResult.Summary, runResult.Turns, tokens),
			Status:  StatusCompleted,
			Tokens:  tokens,
		}

	case killed:
		_ = appendEvent(sp.indexPath, event{
			Kind: "killed", SubSid: sp.subSid, TS: endTS,
		})
		if background {
			return Result{
				SubSid:  sp.subSid,
				Summary: FormatBackgroundFailed(sp.subSid, "killed", "terminated by user via /agents kill"),
				Status:  StatusKilled,
			}
		}
		return Result{
			SubSid:  sp.subSid,
			Summary: FormatFailed(sp.subSid, "killed", "terminated by user via /agents kill"),
			Status:  StatusKilled,
		}

	case errors.Is(runErr, context.Canceled):
		_ = appendEvent(sp.indexPath, event{
			Kind: "failed", SubSid: sp.subSid, TS: endTS, Reason: "canceled",
		})
		if background {
			return Result{
				SubSid:  sp.subSid,
				Summary: FormatBackgroundFailed(sp.subSid, "canceled", "background ctx cancelled (session end or /agents kill)"),
				Status:  StatusFailed,
			}
		}
		return Result{
			SubSid:  sp.subSid,
			Summary: FormatFailed(sp.subSid, "canceled", "parent turn cancelled"),
			Status:  StatusFailed,
		}

	case errors.Is(runErr, context.DeadlineExceeded):
		_ = appendEvent(sp.indexPath, event{
			Kind: "failed", SubSid: sp.subSid, TS: endTS, Reason: "timeout",
		})
		if background {
			return Result{
				SubSid:  sp.subSid,
				Summary: FormatBackgroundFailed(sp.subSid, "timeout", "deadline exceeded"),
				Status:  StatusFailed,
			}
		}
		return Result{
			SubSid:  sp.subSid,
			Summary: FormatFailed(sp.subSid, "timeout", "deadline exceeded"),
			Status:  StatusFailed,
		}

	default:
		// Catch-all: Runner returned an error we don't classify.
		reason := "spawn_error"
		hint := "runner error"
		if runErr != nil {
			hint = runErr.Error()
		} else {
			// runErr == nil but Summary == "" — Runner contract
			// violation. Surface as spawn_error so the LLM can
			// retry; production crash report happens in a future
			// hook.
			hint = "runner returned empty summary with no error (contract violation)"
		}
		_ = appendEvent(sp.indexPath, event{
			Kind: "failed", SubSid: sp.subSid, TS: endTS, Reason: reason,
		})
		if background {
			return Result{
				SubSid:  sp.subSid,
				Summary: FormatBackgroundFailed(sp.subSid, reason, hint),
				Status:  StatusFailed,
			}
		}
		return Result{
			SubSid:  sp.subSid,
			Summary: FormatFailed(sp.subSid, reason, hint),
			Status:  StatusFailed,
		}
	}
}

// Kill cancels the in-flight subagent identified by subSid. Sets
// killedByUser BEFORE invoking cancel so the Spawn goroutine
// observes the flag when it wakes up on ctx.Canceled. Returns
// ErrUnknownSubagent if the subagent isn't currently active
// (already completed, or never existed). Idempotent — calling
// Kill twice in rapid succession is harmless.
func (m *Manager) Kill(subSid string) error {
	m.mu.Lock()
	inf, ok := m.active[subSid]
	if !ok {
		m.mu.Unlock()
		return ErrUnknownSubagent
	}
	inf.killedByUser = true
	m.mu.Unlock()
	// Cancel outside the lock — cancel's listeners may try to
	// re-enter m.mu (via the Spawn goroutine's bookkeeping).
	inf.cancel()
	return nil
}

// ErrUnknownSubagent is returned by Kill when the sub_sid isn't in
// the active map. Callers (TUI, CLI) surface this as "no such
// active subagent" — the failure case is benign.
var ErrUnknownSubagent = errors.New("subagent: unknown or no longer active")

// BackgroundNotice is one terminal-state notification for a
// background-spawned subagent. The Manager's background goroutine
// enqueues it right after writing the terminal index event; the
// Notifier PrePrompt hook drains the queue into the parent session
// as <context> Prepend messages. Summary is the full wire-format
// text ("[agent: background done/failed ...]") — system-written,
// never model-authored (the CC "notification is never something you
// write yourself" contract, PRD §2.1).
type BackgroundNotice struct {
	SubSid      string
	Description string
	Status      Status
	Summary     string
}

// DrainNotices pops every pending notice in FIFO order. Called by
// the Notifier at the start of each parent Prompt so completions
// that stacked up between turns land together in the next one. An
// empty (nil) return is the steady state.
//
// Deliberately destructive: only the delivery path (Notifier) may
// drain. UI surfaces that just want to NAME what finished use
// PendingNotices so they never steal from delivery.
func (m *Manager) DrainNotices() []BackgroundNotice {
	m.noticeMu.Lock()
	defer m.noticeMu.Unlock()
	out := m.pending
	m.pending = nil
	return out
}

// PendingNotices returns a COPY of the queue without draining —
// for UI surfaces (TUI wake hint, status line) that want to name
// what finished without consuming the Notifier's delivery payload.
func (m *Manager) PendingNotices() []BackgroundNotice {
	m.noticeMu.Lock()
	defer m.noticeMu.Unlock()
	out := make([]BackgroundNotice, len(m.pending))
	copy(out, m.pending)
	return out
}

// WakeCh returns the read-only wake signal that fires (capacity 1,
// non-blocking) whenever a notice is enqueued. The TUI arms a
// waitFor-style Cmd on it — the same channel-wake idiom as
// ObserveResultChan — to refresh the agents badge and print the
// "background agent finished" hint without pulling anything off
// the delivery queue.
func (m *Manager) WakeCh() <-chan struct{} { return m.wakeCh }

// enqueueNotice appends to the FIFO and pokes the wake channel.
// Never blocks: a full wake channel just means one wake is already
// pending; the notice itself is safe in the queue (drained in full
// by the Notifier regardless of wake count).
func (m *Manager) enqueueNotice(n BackgroundNotice) {
	m.noticeMu.Lock()
	m.pending = append(m.pending, n)
	m.noticeMu.Unlock()
	select {
	case m.wakeCh <- struct{}{}:
	default:
	}
}

// Shutdown cancels every active subagent (sync + background) and
// waits for background goroutines to finish writing their terminal
// events — the agent-level counterpart of bgjob.Manager.Shutdown
// (v6 柱 K). Wire into the session teardown path: on clean exit
// every background child gets a `failed reason=canceled` terminal
// event, leaving no started-without-terminal residue for the
// orphan scanner to mop up (feature-orchestration PRD §4.1 D3).
//
// Cancel WITHOUT setting killedByUser — Kill is the user-action
// path (`killed` event); Shutdown is lifecycle teardown
// (`failed reason=canceled`).
//
// Blocking contract: waits as long as Runners take to honour ctx
// cancellation (the Runner contract requires a prompt return; a
// pathological Runner that ignores its ctx would hang Shutdown the
// same way it would hang the sync Spawn it belonged to).
func (m *Manager) Shutdown() {
	m.mu.Lock()
	infs := make([]*inFlight, 0, len(m.active))
	for _, inf := range m.active {
		infs = append(infs, inf)
	}
	m.mu.Unlock()
	for _, inf := range infs {
		inf.cancel()
	}
	m.bgWg.Wait()
}

// ListFilter selects which folded Subagent records List returns.
// Empty Status / ParentSid mean "any". Zero value returns all.
type ListFilter struct {
	Status    Status
	ParentSid string
}

// List returns the folded state of every subagent recorded in the
// index, optionally filtered. Reads the index fresh on each call —
// no in-memory cache — so the result reflects events written
// concurrently by other goroutines (or other seek processes
// sharing the same project directory, in theory).
func (m *Manager) List(f ListFilter) ([]Subagent, error) {
	indexPath, err := paths.SubagentsIndex(m.opts.ProjectAbsPath)
	if err != nil {
		return nil, err
	}
	events, err := readEvents(indexPath)
	if err != nil {
		return nil, err
	}
	folded := foldEvents(events)
	if f.Status == "" && f.ParentSid == "" {
		return folded, nil
	}
	out := make([]Subagent, 0, len(folded))
	for _, s := range folded {
		if f.Status != "" && s.Status != f.Status {
			continue
		}
		if f.ParentSid != "" && s.ParentSid != f.ParentSid {
			continue
		}
		out = append(out, s)
	}
	return out, nil
}

// ActiveCount returns the number of currently in-flight subagents.
// Used by the status bar ("⤴ N agents" badge per PRD §4.3) and by
// the agent tool's capacity check display.
func (m *Manager) ActiveCount() int {
	m.mu.Lock()
	defer m.mu.Unlock()
	return len(m.active)
}

// failResult is a small helper for the early-exit paths that
// haven't allocated a sub_sid yet (validation failures). subSid
// may be empty — FormatFailed handles that gracefully.
func failResult(subSid, reason, hint string) Result {
	return Result{
		SubSid:  subSid,
		Summary: FormatFailed(subSid, reason, hint),
		Status:  StatusFailed,
	}
}
