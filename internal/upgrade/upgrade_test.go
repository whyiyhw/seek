func TestParseChecksums(t *testing.T) {
	t.Parallel()
	// Mix of valid lines, comments, and binary-mode '*'.
	body := strings.NewReader(`# generated by goreleaser
abc123` + strings.Repeat("0", 58) + `  seek_0.9.0_linux_amd64.tar.gz
` + strings.Repeat("a", 64) + `  *seek_0.9.0_windows_amd64.zip

short  invalid_line
`)
	sums, err := parseChecksums(body)
	if err != nil {
		t.Fatalf("parseChecksums err: %v", err)
	}
	if len(sums) != 2 {
		t.Fatalf("got %d entries, want 2: %v", len(sums), sums)
	}
	if _, ok := sums["seek_0.9.0_linux_amd64.tar.gz"]; !ok {
		t.Error("missing linux entry")
	}
	if _, ok := sums["seek_0.9.0_windows_amd64.zip"]; !ok {
		t.Error("missing windows entry (binary-mode '*' should be stripped)")
	}
}

