func TestIsDev(t *testing.T) {
	t.Parallel()
	cases := []struct {
		in   string
		want bool
	}{
		{"", true},
		{"dev", true},
		{"unknown", true},
		{"(devel)", true},
		{"v0.0.0-20251122000000-abc123", true},
		{"v0.9.0", false},
		{"0.9.0", false},
		{"v1.0.0-rc.1", false},
		// Formatted banner strings — what tui.VersionString() returns.
		{"dev · abc1234", true},
		{"dev · abc1234+", true},
		{"v0.9.0 · abc1234", false},
		{"v0.9.0 · abc1234+", false},
	}
	for _, c := range cases {
		if got := IsDev(c.in); got != c.want {
			t.Errorf("IsDev(%q) = %v, want %v", c.in, got, c.want)
		}
	}
}

func TestCompareSemver(t *testing.T) {
	t.Parallel()
	cases := []struct {
		a, b string
		want int
	}{
		{"v0.9.0", "v0.9.0", 0},
		{"v0.9.0", "v0.10.0", -1},
		{"v0.10.0", "v0.9.0", +1},
		{"v1.0.0", "v0.99.0", +1},
		{"v1.0.0-rc.1", "v1.0.0", -1}, // pre-release < release
		{"v1.0.0", "v1.0.0-rc.1", +1},
		{"v1.0.0-rc.1", "v1.0.0-rc.2", -1},
		{"dev", "v1.0.0", -1}, // dev always < any release
		{"v1.0.0", "dev", +1},
		{"dev", "dev", 0},
		{"0.9.0", "v0.9.0", 0},                       // tolerant of leading v
		{"v0.9.0 · abc1234", "v0.9.1", -1},           // formatted banner string
		{"v1.0.0 · abc1234+", "v1.0.0", 0},           // formatted banner string, equal core
	}
	for _, c := range cases {
		got := compareSemver(c.a, c.b)
		if got != c.want {
			t.Errorf("compareSemver(%q, %q) = %d, want %d", c.a, c.b, got, c.want)
		}
	}
}

func TestPickAsset(t *testing.T) {
	t.Parallel()
	assets := []ghAsset{
		{Name: "seek_0.9.0_linux_amd64.tar.gz", BrowserDownloadURL: "u1"},
		{Name: "seek_0.9.0_linux_arm64.tar.gz", BrowserDownloadURL: "u2"},
		{Name: "seek_0.9.0_darwin_amd64.tar.gz", BrowserDownloadURL: "u3"},
		{Name: "seek_0.9.0_darwin_arm64.tar.gz", BrowserDownloadURL: "u4"},
		{Name: "seek_0.9.0_windows_amd64.zip", BrowserDownloadURL: "u5"},
		{Name: "seek_0.9.0_checksums.txt", BrowserDownloadURL: "u6"},
	}
	cases := []struct {
		goos, goarch, want string
	}{
		{"linux", "amd64", "u1"},
		{"linux", "arm64", "u2"},
		{"darwin", "amd64", "u3"},
		{"darwin", "arm64", "u4"},
		{"windows", "amd64", "u5"},
		{"darwin", "aarch64", "u4"}, // alias for arm64
		{"linux", "x86_64", "u1"},   // alias for amd64
	}
	for _, c := range cases {
		got, err := pickAsset(assets, c.goos, c.goarch)
		if err != nil {
			t.Errorf("%s/%s: unexpected err %v", c.goos, c.goarch, err)
			continue
		}
		if got.BrowserDownloadURL != c.want {
			t.Errorf("%s/%s: got %s, want %s", c.goos, c.goarch, got.BrowserDownloadURL, c.want)
		}
	}
}

