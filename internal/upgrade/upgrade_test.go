// --- fake GitHub server ---

// fakeReleaseServer simulates the subset of github.com endpoints the
// upgrader hits: /repos/.../releases/latest and the asset download URLs.
// All paths are served from the same httptest.Server; the asset URLs
// are derived from srv.URL so the upgrader's host resolution lines up.
type fakeReleaseServer struct {
	*httptest.Server
	tag              string
	archive          []byte // tar.gz containing "seek"
	checksumsBody    string
	overrideChecksumBody string
	checksumOverride atomic.Pointer[byte] // if non-nil, serve overrideChecksumBody
	reqCount         atomic.Int64
}

func newFakeReleaseServer(t *testing.T, tag string, binaryBytes []byte) *fakeReleaseServer {
	t.Helper()
	mux := http.NewServeMux()
	srv := &fakeReleaseServer{tag: tag}

	srv.archive = makeTarGz(t, map[string][]byte{"seek": binaryBytes})
	archiveName := fmt.Sprintf("seek_%s_linux_amd64.tar.gz", strings.TrimPrefix(tag, "v"))
	srv.checksumsBody = fmt.Sprintf("%s  %s\n", sha256Hex(srv.archive), archiveName)

	mux.HandleFunc("/repos/whyiyhw/seek/releases/latest", func(w http.ResponseWriter, r *http.Request) {
		srv.reqCount.Add(1)
		base := "http://" + r.Host
		body := ghRelease{
			TagName:     tag,
			Name:        "seek " + tag,
			PublishedAt: time.Now().UTC(),
			Assets: []ghAsset{
				{Name: archiveName, BrowserDownloadURL: base + "/dl/" + archiveName, Size: int64(len(srv.archive))},
				{Name: "seek_" + strings.TrimPrefix(tag, "v") + "_checksums.txt", BrowserDownloadURL: base + "/dl/checksums.txt", Size: int64(len(srv.checksumsBody))},
			},
		}
		w.Header().Set("Content-Type", "application/json")
		_ = json.NewEncoder(w).Encode(body)
	})

	mux.HandleFunc("/dl/", func(w http.ResponseWriter, r *http.Request) {
		switch {
		case strings.HasSuffix(r.URL.Path, "checksums.txt"):
			if srv.checksumOverride.Load() != nil {
				_, _ = w.Write([]byte(srv.overrideChecksumBody))
				return
			}
			_, _ = w.Write([]byte(srv.checksumsBody))
		case strings.HasSuffix(r.URL.Path, ".tar.gz"):
			_, _ = w.Write(srv.archive)
		default:
			http.NotFound(w, r)
		}
	})

	srv.Server = httptest.NewServer(mux)
	t.Cleanup(srv.Close)
	return srv
}

// --- archive constructors used by tests ---

func makeTarGz(t *testing.T, files map[string][]byte) []byte {
	t.Helper()
	var buf bytes.Buffer
	gz := gzip.NewWriter(&buf)
	tw := tar.NewWriter(gz)
	for name, content := range files {
		hdr := &tar.Header{
			Name:    name,
			Mode:    0o755,
			Size:    int64(len(content)),
			ModTime: time.Now(),
		}
		if err := tw.WriteHeader(hdr); err != nil {
			t.Fatal(err)
		}
		if _, err := tw.Write(content); err != nil {
			t.Fatal(err)
		}
	}
	if err := tw.Close(); err != nil {
		t.Fatal(err)
	}
	if err := gz.Close(); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

func makeZip(t *testing.T, files map[string][]byte) []byte {
	t.Helper()
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)
	for name, content := range files {
		f, err := zw.Create(name)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := f.Write(content); err != nil {
			t.Fatal(err)
		}
	}
	if err := zw.Close(); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}
