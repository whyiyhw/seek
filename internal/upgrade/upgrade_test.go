func TestExtractTarGz(t *testing.T) {
	t.Parallel()
	want := []byte("#!/bin/sh\necho hi\n")
	archive := makeTarGz(t, map[string][]byte{
		"README.md": []byte("readme"),
		"seek":      want,
	})

	dir := t.TempDir()
	dst := filepath.Join(dir, "out")
	if err := extractBinary(bytes.NewReader(archive), "seek_0.9.0_linux_amd64.tar.gz", "seek", dst); err != nil {
		t.Fatalf("extractBinary: %v", err)
	}
	got, _ := os.ReadFile(dst)
	if !bytes.Equal(got, want) {
		t.Errorf("extracted bytes mismatch")
	}
	if runtime.GOOS != "windows" {
		info, _ := os.Stat(dst)
		if info.Mode()&0o100 == 0 {
			t.Errorf("extracted file not executable: %v", info.Mode())
		}
	}
}

