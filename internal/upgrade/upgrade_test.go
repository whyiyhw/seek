func TestRun_HappyPath(t *testing.T) {
	t.Parallel()
	srv := newFakeReleaseServer(t, "v0.9.1", []byte("new-seek-binary"))
	defer srv.Close()

	exeDir := t.TempDir()
	exePath := filepath.Join(exeDir, "seek")
	if err := os.WriteFile(exePath, []byte("old-seek-binary"), 0o755); err != nil {
		t.Fatal(err)
	}

	var out bytes.Buffer
	res, err := Run(context.Background(), Options{
		Owner:      "whyiyhw",
		Repo:       "seek",
		Current:    "v0.9.0",
		APIBase:    srv.URL,
		HTTPClient: srv.Client(),
		GOOS:       "linux",
		GOARCH:     "amd64",
		ExePath:    exePath,
		Stderr:     &out,
		Stdout:     io.Discard,
	})
	if err != nil {
		t.Fatalf("Run: %v\nstderr:\n%s", err, out.String())
	}
	if res.AlreadyLatest {
		t.Error("expected AlreadyLatest=false")
	}
	if res.To != "v0.9.1" {
		t.Errorf("To = %q, want v0.9.1", res.To)
	}
	got, _ := os.ReadFile(exePath)
	if !bytes.Equal(got, []byte("new-seek-binary")) {
		t.Errorf("binary not replaced: got %q", got)
	}
}

