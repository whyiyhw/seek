// schemaBytes is the ACTIVE JSON schema for the `agent` tool.
//
// Since P2-c (feature-orchestration.md §5 D12, M-O2.2) the
// `subagent_type` enum is DYNAMIC: generated at startup from the
// typed-agent registry (project + user files, config overrides,
// built-ins) instead of the closed three-value enum. The byte
// discipline that keeps DeepSeek's prefix cache alive:
//
//   - built ONCE per process — the package var is the cache; Schema()
//     never regenerates, so bytes are stable across turns;
//   - DETERMINISTIC for a given registry — Set.List() order is
//     insertion order (sorted filenames per scope, sorted config
//     keys, fixed built-in order), so the same config on two
//     launches yields byte-identical schemas (the acceptance口径
//     "同配置多次启动间字节一致");
//   - cross-launch changes with the config = one accepted bust (same
//     precedent as bash's run_in_background field).
//
// The default value (no CacheTypesSchema call) is generated from
// agenttypes.Builtins() — i.e. no agents files + empty config keeps
// the three built-ins in the enum, the acceptance-#5 guarantee.
//
// Mirrors docs/prd/archive/feature-subagent.md §3.1 verbatim with one
// deviation: `maxLength` is omitted from the `description` field
// because tools.UnmarshalStrict doesn't enforce JSON Schema length
// constraints (only DisallowUnknownFields). Length is enforced in
// Execute via the explicit guards documented in the PRD as
// "Execute-side strict, schema-side advisory".
var schemaBytes = buildSchema(agenttypes.Builtins())

// activeDescription is the tool description = static base + the
// dynamic type-list tail (D12: "工具 description 尾段"). Cached and
// frozen alongside schemaBytes by CacheTypesSchema.
var activeDescription = descriptionBase + " " + typesTail(agenttypes.Builtins())

// CacheTypesSchema freezes the dynamic schema (enum + per-value
// descriptions + description tail) for THIS process from the given
// registry. cmd/seek calls it ONCE at startup, right after
// agenttypes.Load and BEFORE the tool is registered — the same
// per-process freeze as the skill manifest. Calling it again later is
// a programming error (bytes must not drift mid-process); the
// package var assignment is unsynchronised by design, startup is
// single-threaded.
func CacheTypesSchema(defs []*agenttypes.Definition) {
	schemaBytes = buildSchema(defs)
	activeDescription = descriptionBase + " " + typesTail(defs)
}

// maxTypeDescRunes caps one type's contribution to the schema
// description (D12: "描述长度设上限（~200 字/type），防 schema 膨胀").
const maxTypeDescRunes = 200

