#!/usr/bin/env bash
# Generate the fixture into a per-case scratch dir (eval/run.sh setup
# hook). Deterministic on purpose: every gold answer is arithmetic, not a
# snapshot of the repo, so the case does not rot when seek's own source
# moves.
#
# Two parts, because they probe two DIFFERENT affordance holes:
#
#   src/*.go + src/README.md + src/notes.txt   (mixed extensions, small)
#         core.go     ALPHA  BETA   GAMMA x2
#         util.go     ALPHA  -      GAMMA x3
#         extra.go    ALPHA  -      GAMMA x1
#         README.md   ALPHA  BETA   GAMMA x5
#         notes.txt   ALPHA  BETA   GAMMA x4
#
#   src/gen/*.go                               (bulk, GAMMA-only)
#       6 generated files, 940 GAMMA marker lines between them. This is
#       the part the grep tool genuinely CANNOT answer: it caps at
#       max_matches 200 and its "capped" notice reports the CAPPED hit
#       count, not the true total (see eval/cases/grep-refine-not-flood/
#       README.md) — no number of paging greps ever yields 940. A
#       count-only argument (or a shell pipeline) is the only exact
#       expression. Lines are ~100 chars, so paging `read` is not a
#       cheap side door (~94 KiB of matches).
#
# Gold (the four questions in prompt.txt; asserted at the end):
#   Q1  .go files in src/ containing MarkerALPHA            -> 3
#   Q2  of those, the ones WITHOUT MarkerBETA               -> util.go, extra.go
#   Q3  total MarkerGAMMA occurrences across ALL .go under src/  -> 946
#   Q4  of that 946, how many are in src/gen/*.go           -> 940
set -e
base=eval/tmp/grep-affordance
dir=$base/src
rm -rf "$base"
mkdir -p "$dir/gen"

# emit FILE ALPHA? BETA? GAMMA_COUNT
emit() {
  f="$dir/$1"; alpha=$2; beta=$3; n=$4
  {
    printf '// synthetic fixture for eval/cases/grep-affordance\n'
    [ "$alpha" = "1" ] && printf 'const MarkerALPHA = "present"\n'
    [ "$beta" = "1" ] && printf 'const MarkerBETA = "present"\n'
    i=1
    while [ "$i" -le "$n" ]; do
      printf 'const MarkerGAMMA%d = %d\n' "$i" "$i"
      i=$((i + 1))
    done
    printf 'func Useful() string { return "ok" }\n'
  } > "$f"
}

emit core.go   1 1 2
emit util.go   1 0 3
emit extra.go  1 0 1
emit README.md 1 1 5
emit notes.txt 1 1 4

# Generated files: GAMMA only, no ALPHA/BETA, so Q1/Q2 are unaffected
# by their presence. 4 files x 157 + 2 files x 156 = 628 + 312 = 940.
idx=0
while [ "$idx" -lt 6 ]; do
  f=$(printf '%s/gen/g%02d.go' "$dir" "$idx")
  n=156
  [ "$idx" -lt 4 ] && n=157
  {
    printf '// Code generated by setup.sh for eval/cases/grep-affordance. DO NOT EDIT.\n'
    printf 'package gen\n'
    i=1
    while [ "$i" -le "$n" ]; do
      printf 'var Emit%04d = buildRecord("MarkerGAMMA", %04d, "tenant-acme-synthetic-fixture-record")\n' "$i" "$i"
      i=$((i + 1))
    done
  } > "$f"
  idx=$((idx + 1))
done

# Sanity-check the contract; fail loudly if it drifted.
q1=$(grep -l MarkerALPHA "$dir"/*.go | wc -l | tr -d ' ')
q2=$(grep -L MarkerBETA "$dir"/*.go | wc -l | tr -d ' ')
q3=$(cat "$dir"/*.go "$dir"/gen/*.go | grep -o MarkerGAMMA | wc -l | tr -d ' ')
q4=$(cat "$dir"/gen/*.go | grep -o MarkerGAMMA | wc -l | tr -d ' ')
if [ "$q1" -ne 3 ] || [ "$q2" -ne 2 ] || [ "$q3" -ne 946 ] || [ "$q4" -ne 940 ]; then
  echo "grep-affordance setup: fixture contract drifted (Q1=$q1 want 3, Q2=$q2 want 2, Q3=$q3 want 946, Q4=$q4 want 940)" >&2
  exit 1
fi
